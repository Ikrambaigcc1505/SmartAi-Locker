  signingConfigs {
    create("release") {
      val propOrEnv: (String, String?) -> String? = { propKey, envKey ->
        (project.findProperty(propKey) as? String)?.takeIf { it.isNotBlank() }
          ?: envKey?.let { System.getenv(it) }?.takeIf { it.isNotBlank() }
      }
      val configuredPath = propOrEnv("KEYSTORE_FILE", "KEYSTORE_FILE")
        ?: propOrEnv("KEYSTORE_PATH", "KEYSTORE_PATH")
        ?: propOrEnv("ANDROID_KEYSTORE_PATH", "ANDROID_KEYSTORE_PATH")
      val configuredFile = configuredPath?.let { file(it) }
      val defaultUploadKey = file("${rootDir}/my-upload-key.jks")
      val resolvedKeystore = when {
        configuredFile != null && configuredFile.exists() -> configuredFile
        defaultUploadKey.exists() -> defaultUploadKey
        else -> null
      }
      val resolvedStorePass = propOrEnv("KEYSTORE_PASSWORD", "KEYSTORE_PASSWORD")
        ?: propOrEnv("STORE_PASSWORD", "STORE_PASSWORD")
        ?: propOrEnv("ANDROID_KEYSTORE_PASSWORD", "ANDROID_KEYSTORE_PASSWORD")
      val resolvedAlias = propOrEnv("KEY_ALIAS", "KEY_ALIAS")
        ?: propOrEnv("ANDROID_KEY_ALIAS", "ANDROID_KEY_ALIAS")
        ?: "upload"
      val resolvedKeyPass = propOrEnv("KEY_PASSWORD", "KEY_PASSWORD")
        ?: propOrEnv("ANDROID_KEY_PASSWORD", "ANDROID_KEY_PASSWORD")
        ?: resolvedStorePass

      if (resolvedKeystore != null && !resolvedStorePass.isNullOrBlank() && !resolvedKeyPass.isNullOrBlank()) {
        storeFile = resolvedKeystore
        storePassword = resolvedStorePass
        keyAlias = resolvedAlias
        keyPassword = resolvedKeyPass
      } else {
        storeFile = file("${rootDir}/debug.keystore")
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

